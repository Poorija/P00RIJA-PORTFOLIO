export type Art = { shape: string[]; mask?: string[]; color: string };

const art = (shape: string, mask: string | null, color: string): Art => ({
  shape: shape.replaceAll("§", "`").replace(/^\n|\n$/g, "").split("\n"),
  mask: mask?.replace(/^\n|\n$/g, "").split("\n"),
  color,
});

